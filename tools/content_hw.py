def _build(num):
    src = _BY_NUM[num]
    hw = HW[num]
    figs = hw.get("figs") or [dict(t=d["t"], svg=d["svg"], cap=d.get("cap", ""))
                              for d in src["diagrams"]]
    sides = hw.get("sides", {})
    blocks, secno = [], 0

    for entry in hw["plan"]:
        kind = entry[0]
        if kind == "s":
            _, i, span = entry
            secno += 1
            b = src["boxes"][i]
            blocks.append(dict(type="sec", n=secno, t=b["t"], en=b.get("en"),
                               items=b["items"], span=span))
        elif kind == "f":
            _, i, span = entry
            f = figs[i]
            blocks.append(dict(type="fig", t=f["t"], svg=f["svg"],
                               cap=f.get("cap", ""), span=span))
        elif kind == "b":
            _, key, span = entry
            s = sides[key]
            blocks.append(dict(type="side", t=s["t"], en=s.get("en"),
                               items=s["items"], span=span))
        elif kind == "facts":
            blocks.append(dict(type="facts", items=src["must"], span=entry[1]))
        elif kind == "pyq":
            blocks.append(dict(type="pyq", items=src["pyq"], span=entry[1]))
        else:
            raise ValueError(kind)

    return dict(
        num=num, slug=src["slug"], hi=src["hi"], en=src["en"],
        unit_no=UNIT_NO[num], unit_name=src["unit_name"].split(" (")[0],
        unit_marks=src["unit_marks"],
        intro=hw["intro"], blocks=blocks,
        flow=hw.get("flow"), flow_title=hw.get("flow_title"),
    )


CHAPTERS_HW = [_build(n) for n in sorted(HW)]
